#!/usr/bin/env node
/* Generates the single-file dashboard paste for the mcp function: core.js
   inlined AT the import site (replacing the import line), so every
   declaration precedes its first top-level use and no local import remains.
   The drift gate (tests/mcp-scheme.test.mjs) regenerates this and compares
   byte for byte, so the paste can never fall behind the sources.
   v2.51 deploy finding: the previous generator matched only single-quote
   imports and appended core at the tail; the paste kept its "./core.js"
   import and the Deno bundler refused it (Module not found). Caught live,
   fixed here, and gated below. */
import { readFileSync, writeFileSync } from 'node:fs';
const dir = 'supabase/functions/mcp/';
const unexport = (src) => src
  .split('\n')
  .map((l) => l.replace(/^export function /, 'function ').replace(/^export async function /, 'async function ').replace(/^export const /, 'const '))
  .join('\n');
const core = unexport(readFileSync(dir + 'core.js', 'utf8'));
const handler = unexport(readFileSync(dir + 'index.ts', 'utf8'));
const importRe = /^import \{[^}]*\} from ["']\.\/core\.js["'];\n/m;
if (!importRe.test(handler)) throw new Error('index.ts must import ./core.js exactly once');
const coreBlock = '// ---- inlined supabase/functions/mcp/core.js ----\n' + core.trimEnd() + '\n\n';
const inlined = handler.replace(importRe, coreBlock);
if (inlined.includes('./core.js')) throw new Error('import survived inlining');
const out = '// GENERATED by scripts/bundle-mcp-function.mjs. Do not edit; edit\n'
  + '// supabase/functions/mcp/index.ts and core.js, then regenerate.\n'
  + '// Paste this whole file over the deployed mcp function. Verify JWT OFF.\n\n'
  + inlined + '\n\n';
writeFileSync(dir + 'dist/index.ts', out);
console.log('bundled: ' + out.length + ' bytes -> ' + dir + 'dist/index.ts');
