#!/usr/bin/env node
/* Generates the single-file dashboard paste for the seal-receipt function:
   the exact core.js and seallib.mjs sources inlined below the handler's
   imports, exports and local imports stripped, nothing else changed. The
   drift gate (tests/seal-bundle.test.mjs) regenerates this and compares
   byte for byte, so the paste can never fall behind the sources. */
import { readFileSync, writeFileSync } from 'node:fs';
const dir = 'supabase/functions/seal-receipt/';
const strip = (src, dropImports) => src
  .split('\n')
  .filter((l) => !(dropImports && /^import .+ from '\.\/(core|seallib)/.test(l)))
  .map((l) => l.replace(/^export function /, 'function ').replace(/^export async function /, 'async function ').replace(/^export const /, 'const '))
  .join('\n');
const core = strip(readFileSync(dir + 'core.js', 'utf8'), false);
const lib = strip(readFileSync(dir + 'seallib.mjs', 'utf8'), true)
  .replace("import { createPrivateKey, createPublicKey, sign as edSign, verify as edVerify } from 'node:crypto';",
           "import { createPrivateKey, createPublicKey, sign as edSign, verify as edVerify } from 'node:crypto';");
let idx = readFileSync(dir + 'index.ts', 'utf8');
idx = idx.replace(/^import \{ buildReceipt.+seallib\.mjs";\n/m, '');
idx = idx.replace('const { verifyReceiptHash } = await import("./seallib.mjs");\n            ', '');
const out = [
  '// SINGLE-FILE DASHBOARD PASTE for the seal-receipt edge function.',
  '// Generated by scripts/bundle-seal-function.mjs from index.ts, seallib.mjs,',
  '// and core.js. Do not edit by hand: regenerate, the drift gate compares.',
  '',
  '// ---- inlined app/js/core.js (byte-verified against the app) ----',
  core,
  '// ---- inlined seallib.mjs ----',
  lib,
  '// ---- the handler (index.ts) ----',
  idx,
].join('\n');
writeFileSync(dir + 'dist/index.ts', out);
console.log('bundled: ' + out.length + ' bytes -> ' + dir + 'dist/index.ts');
